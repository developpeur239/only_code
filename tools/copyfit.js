// copyfit.js - copy-synthesis of consonant gestures.
// For each consonant, Nelder-Mead adjusts its gesture (duration, closing and opening speeds, place, width, constriction,
// voicing, burst) so that the model saying « je dis _a » with the speaker's measured timing, pitch and loudness sounds
// as close as possible to the speaker's own recordings: MFCC distance after DTW alignment, over the window of the word.
// The recordings are only a measurement target; nothing of them goes into the film.
//
//   node tools/copyfit.js HUMAN_LIST.json [consonants...]      -> src/audio/consfit.js, qa/copyfit.md
//   (runs one worker per consonant, as many at once as there are cores)
'use strict';
const fs = require('fs'), path = require('path'), os = require('os'), cp = require('child_process');
const ROOT = path.resolve(__dirname, '..');

// parameters per kind: [field, default, lo, hi, log?]
const SPACE = {
  s: [['d', null, .04, .2, 1], ['tc', .009, .003, .04, 1], ['to', .008, .003, .04, 1], ['u', null, -.06, .06, 0], ['w', null, .3, 2.5, 1], ['gb', null, null, null, 1], ['bt', .0094, .002, .03, 1], ['vx', null, 0, 1, 0]],
  f: [['d', null, .04, .2, 1], ['tc', .01, .003, .04, 1], ['to', .009, .003, .04, 1], ['u', null, -.06, .06, 0], ['w', null, .3, 2.5, 1], ['Ac', null, .02, .5, 1], ['g', null, null, null, 1]],
  n: [['d', null, .04, .2, 1], ['tc', .009, .003, .04, 1], ['to', .008, .003, .04, 1], ['u', null, -.06, .06, 0], ['w', null, .3, 2.5, 1]],
  l: [['d', null, .04, .2, 1], ['tc', .012, .003, .04, 1], ['to', .01, .003, .04, 1], ['u', null, -.06, .06, 0], ['w', null, .3, 2.5, 1], ['Ac', null, .03, .6, 1]],
};
const WORD = { p: 'pas', b: 'bas', t: 'tas', k: 'cas', g: 'gars', f: 'fa', v: 'va', s: 'ça', S: 'chat', m: 'ma', l: 'la', R: 'rat' };

if (process.argv[2] === '--worker') worker(process.argv[3], process.argv[4]);
else master();

function master() {
  const list = process.argv[2], want = process.argv.slice(3).length ? process.argv.slice(3) : Object.keys(WORD);
  const n = Math.max(1, os.cpus().length), queue = want.slice(), results = {};
  let running = 0;
  const t0 = Date.now();
  const next = () => {
    if (!queue.length) { if (!running) finish(); return; }
    const c = queue.shift(); running++;
    const ch = cp.fork(__filename, ['--worker', list, c], { stdio: ['ignore', 'pipe', 'inherit', 'ipc'] });
    ch.on('message', m => { results[c] = m; console.log(`${c}: margin ${m.before.toFixed(2)} -> ${m.after.toFixed(2)} (negative = closer to its own word than to any other)  (${((Date.now() - t0) / 1000).toFixed(0)} s)`); });
    ch.on('exit', () => { running--; next(); });
  };
  for (let i = 0; i < n; i++) next();
  function finish() {
    const file = path.join(ROOT, 'src/audio/consfit.js');
    let old = {}; try { old = require(file) || {}; } catch (e) {}
    for (const [c, r] of Object.entries(results)) old[c] = r.params;
    fs.writeFileSync(file, '// consfit.js - generated by tools/copyfit.js (copy-synthesis of consonant gestures). Do not edit.\nconst CONSFIT = ' + JSON.stringify(old) + ';\nif (typeof module !== \'undefined\') module.exports = CONSFIT;\n');
    const rows = Object.entries(results).map(([c, r]) => `| ${c} (${WORD[c]}) | ${r.before.toFixed(2)} | ${r.after.toFixed(2)} | ${r.human.toFixed(2)} | ${Object.entries(r.params).map(([k, v]) => `${k} ${+v.toPrecision(3)}`).join(', ')} |`);
    fs.writeFileSync(path.join(ROOT, 'qa/copyfit.md'), '# Synthèse par copie des consonnes\n\nMarge discriminante (MFCC alignés par DTW, fenêtre de la consonne et de sa transition) : distance du mot synthétique au même mot humain, moins sa distance (softmin) aux autres mots humains. Négative = le modèle ressemble plus au bon mot qu\'aux autres.\n\n| consonne | marge avant | marge après | entre deux prises humaines | gestes ajustés |\n|---|---|---|---|---|\n' + rows.join('\n') + '\n');
    console.log('wrote src/audio/consfit.js and qa/copyfit.md');
  }
  next.toString();
}

function worker(listFile, c) {
  global.POSTURES = require('../src/audio/postures.js');
  global.CONSFIT = {};   // start from the hand-set gestures
  const V = require('../src/audio/voice.js'), D = require('./dsp.js'), P = require('./prosody.js');
  const L = JSON.parse(fs.readFileSync(listFile, 'utf8')), root = path.dirname(path.dirname(listFile)), word = WORD[c];
  // the window: the consonant and its transition into the vowel, where the cues that tell consonants apart live
  const win = m => [m.nuclei[2] - .2, Math.min(m.end, m.nuclei[2] + .12)];
  const all = L.items.filter(i => i.set === 'cons').map(i => {
    const m = P.measure(path.join(root, i.file), i.word); const [a, b] = win(m);
    return { word: i.word, m, a, b, ref: D.mfcc(m.x, m.sr, Math.round(a * m.sr), Math.round(b * m.sr)) };
  });
  const takes = all.filter(T => T.word === word), others = all.filter(T => T.word !== word);
  const human = takes.length > 1 ? D.dtw(takes[0].ref, takes[1].ref) : 0;
  const C = V.CONS[c], kind = C.k === 'g' ? 'l' : C.k, space = SPACE[kind];
  const U0 = { lab: .995, tip: .905, pal: .80, dpal: .80, dor: .7, uvu: .6 }[C.pl];
  const base = {};
  for (const [f, def] of space) base[f] = f === 'u' ? 0 : f === 'vx' ? (C.vl ? .022 / .06 : .6) : C[f] !== undefined ? C[f] : def;
  const decode = x => {
    const p = {};
    space.forEach(([f, def, lo, hi, lg], i) => {
      let v;
      if (f === 'g' || f === 'gb') v = base[f] * Math.exp(Math.max(-3.4, Math.min(3.4, x[i])));
      else if (lg) v = Math.max(lo, Math.min(hi, base[f] * Math.exp(x[i])));
      else v = Math.max(lo, Math.min(hi, base[f] + x[i]));
      p[f] = v;
    });
    const out = {};
    for (const [f, v] of Object.entries(p)) {
      if (f === 'u') { if (U0 !== undefined && C.pl !== 'dor') out.u = U0 + v; }
      else if (f === 'vx') { if (C.vl) out.vot = v * .06; else out.vb = v; }
      else out[f] = v;
    }
    return out;
  };
  // discriminative: how much closer the model's word is to the speaker's same word than to the speaker's other words.
  // Both voices share the vowel, so the difference in timbre between them cancels; what remains is the consonant.
  const softmin = (v, tau = .5) => { const m = Math.min(...v); return m - tau * Math.log(v.reduce((s, x) => s + Math.exp(-(x - m) / tau), 0)); };
  let lastSame = 0;
  const dist = params => {
    Object.assign(V.CONS[c], params);
    let tot = 0, same = 0;
    for (const T of takes) {
      const r = V.sing('grandpa', T.m.syl, { seed: 5, tail: .25, f0: T.m.f0, amp: T.m.amp });
      const mix = new Float64Array(Math.ceil((T.b + .3) * 44100)), o = Math.round(r.t0 * 44100);
      for (let i = 0; i < r.pcm.length && o + i < mix.length; i++) if (o + i >= 0) mix[o + i] += r.pcm[i];
      const M = D.mfcc(mix, 44100, Math.round(T.a * 44100), Math.round(T.b * 44100));
      const dS = Math.min(...takes.map(H => D.dtw(M, H.ref))), dO = softmin(others.map(H => D.dtw(M, H.ref)));
      tot += dS - dO; same += dS;
    }
    lastSame = same / takes.length;
    return tot / takes.length;
  };
  const x0 = space.map(() => 0);
  const before = dist(decode(x0));
  const cost = x => dist(decode(x)) + .02 * x.reduce((s, v) => s + v * v, 0);
  // Nelder-Mead
  const n = x0.length; let S = [x0.slice()]; for (let i = 0; i < n; i++) { const x = x0.slice(); x[i] += .5; S.push(x); }
  let F = S.map(cost);
  for (let it = 0; it < 70; it++) {
    const ord = F.map((f, i) => [f, i]).sort((a, b) => a[0] - b[0]); S = ord.map(o => S[o[1]]); F = ord.map(o => o[0]);
    const cen = new Array(n).fill(0); for (let i = 0; i < n; i++) for (let j = 0; j < n; j++) cen[j] += S[i][j] / n;
    const at = k => cen.map((cj, j) => cj + k * (S[n][j] - cj));
    const xr = at(-1), fr = cost(xr);
    if (fr < F[0]) { const xe = at(-2), fe = cost(xe); if (fe < fr) { S[n] = xe; F[n] = fe; } else { S[n] = xr; F[n] = fr; } }
    else if (fr < F[n - 1]) { S[n] = xr; F[n] = fr; }
    else { const xc = at(.5), fc = cost(xc); if (fc < F[n]) { S[n] = xc; F[n] = fc; } else for (let i = 1; i <= n; i++) { S[i] = S[i].map((v, j) => S[0][j] + .5 * (v - S[0][j])); F[i] = cost(S[i]); } }
  }
  const b = F.indexOf(Math.min(...F)), params = decode(S[b]);
  const after = dist(params);
  process.send({ before, after, same: lastSame, human, params });
  process.exit(0);
}

// fit.js - finds the tongue and lip posture of every French vowel by measurement, not by ear.
// For each vowel: Nelder-Mead over (q1, q2, lip) so that the tract's own impulse response puts
// F1-F3 on published adult-male targets. Writes src/audio/postures.js and qa/vowels.md.
// usage: node tools/fit.js [vowel ...]
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
global.POSTURES = null;
const V = require('../src/audio/voice.js'), D = require('./dsp.js');

// adult male French, Hz (rounded from Calliope 1989 and Gendrot & Adda-Decker 2005 means)
// nasal vowels: the oral substrate under the lowered velum
const TARGET = {
  i: [300, 2150, 3000], e: [370, 2000, 2650], E: [520, 1750, 2500], a: [680, 1350, 2500],
  O: [520, 1050, 2450], o: [390, 850, 2350], u: [310, 780, 2250], y: [300, 1750, 2150],
  '2': [380, 1450, 2250], '9': [520, 1400, 2350], '@': [470, 1450, 2400],
  'a~': [630, 1050, 2500], 'o~': [440, 820, 2350], 'e~': [580, 1550, 2500], '9~': [540, 1400, 2400],
};
const IRN = 8192;
function measure(singer, P) { const ir = V.impulse(singer, P, IRN); return D.formantsIR(ir, ir.fs); }
function minTongueArea(P) {
  const T = V.Tract(V.SINGERS.grandpa), A = new Float64Array(T.N); V.areas(T.N, 1, P, A);
  let m = 1e9, M = 0; for (let i = 2; i < T.N - 5; i++) { m = Math.min(m, A[i]); M = Math.max(M, A[i]); } return [m, M];
}
function cost(v, x) {
  const [q1, q2, lip, q3] = x, rnd = V.ROUND[v];
  let pen = 0;
  if (Math.abs(q3) > 1) pen += (Math.abs(q3) - 1) * 50; if (Math.abs(q1) > 2) pen += (Math.abs(q1) - 2) * 50; if (Math.abs(q2) > 2) pen += (Math.abs(q2) - 2) * 50;
  if (lip < .08) pen += (.08 - lip) * 200; if (lip > 6) pen += (lip - 6) * 10;
  // rounded vowels keep a small mouth, spread ones an open one
  if (rnd >= .8 && lip > 1.6) pen += (lip - 1.6) * 2; if (rnd === 0 && lip < 1.2) pen += (1.2 - lip) * 2;
  const P = { q1, q2, q3, lip: Math.max(.05, lip), rnd, cons: [] };
  // anatomy: no vowel closes below 0.25 cm2 and no cavity swells past 7 cm2
  const [mA, MA] = minTongueArea(P); if (mA < .25) pen += (.25 - mA) * 40; if (MA > 7) pen += (MA - 7) * .5;
  const f = measure('grandpa', P), t = TARGET[v];
  if (f.length < 3) return 50 + pen;
  let c = 0; const w = [1.2, 1, .45];
  for (let k = 0; k < 3; k++) { const e = Math.log(f[k].f / t[k]); c += w[k] * e * e; }
  return c * 100 + pen + .002 * (q1 * q1 + q2 * q2) + .02 * q3 * q3;
}
function nelder(fn, x0, step, iters = 160) {
  const n = x0.length; let S = [x0.slice()];
  for (let i = 0; i < n; i++) { const x = x0.slice(); x[i] += step[i]; S.push(x); }
  let F = S.map(fn);
  for (let it = 0; it < iters; it++) {
    const ord = F.map((f, i) => [f, i]).sort((a, b) => a[0] - b[0]); S = ord.map(o => S[o[1]]); F = ord.map(o => o[0]);
    const c = new Array(n).fill(0); for (let i = 0; i < n; i++) for (let j = 0; j < n; j++) c[j] += S[i][j] / n;
    const at = k => c.map((cj, j) => cj + k * (S[n][j] - cj));
    const xr = at(-1), fr = fn(xr);
    if (fr < F[0]) { const xe = at(-2), fe = fn(xe); if (fe < fr) { S[n] = xe; F[n] = fe; } else { S[n] = xr; F[n] = fr; } }
    else if (fr < F[n - 1]) { S[n] = xr; F[n] = fr; }
    else { const xc = at(.5), fc = fn(xc); if (fc < F[n]) { S[n] = xc; F[n] = fc; } else { for (let i = 1; i <= n; i++) { S[i] = S[i].map((v, j) => S[0][j] + .5 * (v - S[0][j])); F[i] = fn(S[i]); } } }
  }
  const b = F.indexOf(Math.min(...F)); return { x: S[b], f: F[b] };
}
function fitVowel(v) {
  let best = null;
  const lip0 = V.ROUND[v] >= .8 ? .6 : V.ROUND[v] > 0 ? 1.6 : 3;
  for (const q1 of [-1.2, 0, 1.2]) for (const q2 of [-1, 0, 1]) {
    const r = nelder(x => cost(v, x), [q1, q2, lip0, 0], [.4, .4, lip0 * .4, .25], 90);
    if (!best || r.f < best.f) best = r;
  }
  best = nelder(x => cost(v, x), best.x, [.15, .15, best.x[2] * .2, .1], 220);
  return best;
}

const want = process.argv.slice(2).length ? process.argv.slice(2) : Object.keys(TARGET);
const file = path.join(ROOT, 'src/audio/postures.js');
let old = {}; try { old = require(file) || {}; } catch (e) {}
const res = Object.assign({}, old);
const t0 = Date.now();
for (const v of want) {
  const r = fitVowel(v), key = v.replace('~', 'N');
  res[key] = r.x.map(x => +x.toFixed(4));
  const f = measure('grandpa', { q1: r.x[0], q2: r.x[1], lip: r.x[2], q3: r.x[3], rnd: V.ROUND[v], cons: [] });
  console.log(v.padEnd(3), 'cost', r.f.toFixed(3), 'F', f.slice(0, 3).map(p => Math.round(p.f)).join('/'), 'target', TARGET[v].join('/'), ((Date.now() - t0) / 1000).toFixed(0) + 's');
}
fs.writeFileSync(file, '// postures.js - generated by tools/fit.js. Do not edit: run `node tools/fit.js`.\n// vowel: [q1 (cm), q2 (cm), lip opening (cm2), q3 (cm)]  (nasal vowels: the oral substrate, key with N)\nconst POSTURES = ' + JSON.stringify(res, null, 0).replace(/],/g, '],\n  ').replace('{', '{\n  ') + ';\nif (typeof module !== \'undefined\') module.exports = POSTURES;\n');

// the report: every singer, measured against the male target scaled by tract length
const rows = [];
for (const v of Object.keys(TARGET)) {
  const p = res[v.replace('~', 'N')]; if (!p) continue;
  const P = { q1: p[0], q2: p[1], lip: p[2], q3: p[3] || 0, rnd: V.ROUND[v], cons: [] };
  const cells = [];
  for (const s of ['grandpa', 'grandma', 'child']) {
    const k = 17.6 / V.SINGERS[s].L, f = measure(s, P).slice(0, 3), t = TARGET[v].map(x => x * k);
    const err = f.length < 3 ? NaN : Math.max(...f.map((q, i) => Math.abs(q.f / t[i] - 1) * 100));
    cells.push(f.map(q => Math.round(q.f)).join(' / ') + ` (${err.toFixed(1)} %)`);
  }
  rows.push(`| ${v} | ${TARGET[v].join(' / ')} | ${cells.join(' | ')} |`);
}
fs.mkdirSync(path.join(ROOT, 'qa'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'qa/vowels.md'), `# Voyelles : formants mesurés\n\nRéponse impulsionnelle du conduit, F1 / F2 / F3 en Hz. Entre parenthèses : écart maximal à la cible (cible homme × 17,6 / longueur du conduit).\n\n| voyelle | cible (homme) | grand-père | grand-mère | enfant |\n|---|---|---|---|---|\n${rows.join('\n')}\n`);
console.log('wrote postures.js and qa/vowels.md');

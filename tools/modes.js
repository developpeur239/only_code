// modes.js SHAPES.json - learns the articulatory modes of a real voice from its inverted tube shapes
// (principal components of the shape coefficients, as Story & Titze did from MRI), then measures, for M = 2..8 modes,
// how well a tract restricted to the first M modes can still reproduce the recording (the same ceiling test).
// Writes src/audio/modes.js.
'use strict';
const fs = require('fs'), path = require('path');
const [shapesFile] = process.argv.slice(2);
const S = JSON.parse(fs.readFileSync(shapesFile, 'utf8')), K = S.K;
const X = []; for (const u of S.utts) for (const f of u.frames) X.push(f.x.slice(1));      // the K shape coefficients (lip handled apart)
const lips = []; for (const u of S.utts) for (const f of u.frames) lips.push(f.x[0]);
const n = X.length, mean = new Array(K).fill(0); X.forEach(x => x.forEach((v, k) => mean[k] += v / n));
const C = Array.from({ length: K }, () => new Array(K).fill(0));
X.forEach(x => { for (let i = 0; i < K; i++) for (let j = 0; j < K; j++) C[i][j] += (x[i] - mean[i]) * (x[j] - mean[j]) / (n - 1); });
// Jacobi eigen-decomposition
function jacobi(A) {
  const m = A.length, a = A.map(r => r.slice()), v = Array.from({ length: m }, (_, i) => Array.from({ length: m }, (_, j) => +(i === j)));
  for (let sweep = 0; sweep < 100; sweep++) {
    let off = 0; for (let i = 0; i < m; i++) for (let j = i + 1; j < m; j++) off += a[i][j] ** 2; if (off < 1e-14) break;
    for (let p = 0; p < m; p++) for (let q = p + 1; q < m; q++) {
      if (Math.abs(a[p][q]) < 1e-15) continue;
      const th = (a[q][q] - a[p][p]) / (2 * a[p][q]), t = Math.sign(th || 1) / (Math.abs(th) + Math.sqrt(th * th + 1)), c = 1 / Math.sqrt(t * t + 1), s = t * c;
      for (let k = 0; k < m; k++) { const akp = a[k][p], akq = a[k][q]; a[k][p] = c * akp - s * akq; a[k][q] = s * akp + c * akq; }
      for (let k = 0; k < m; k++) { const apk = a[p][k], aqk = a[q][k]; a[p][k] = c * apk - s * aqk; a[q][k] = s * apk + c * aqk; }
      for (let k = 0; k < m; k++) { const vkp = v[k][p], vkq = v[k][q]; v[k][p] = c * vkp - s * vkq; v[k][q] = s * vkp + c * vkq; }
    }
  }
  const vals = a.map((r, i) => r[i]), idx = vals.map((x, i) => i).sort((i, j) => vals[j] - vals[i]);
  return { vals: idx.map(i => vals[i]), vecs: idx.map(i => v.map(r => r[i])) };
}
const { vals, vecs } = jacobi(C), tot = vals.reduce((s, x) => s + x, 0);
let cum = 0; console.log('variance expliquée par mode : ' + vals.map(v => { cum += v; return (100 * cum / tot).toFixed(0) + '%'; }).join(' '));
const lipMean = lips.reduce((s, v) => s + v, 0) / lips.length;
const out = { K, mean, sd: vals.map(Math.sqrt), modes: vecs, lipMean, frames: n, from: path.basename(shapesFile) };
fs.writeFileSync(path.resolve(__dirname, '../src/audio/modes.js'), '// modes.js - generated by tools/modes.js: articulatory modes learned from a real voice (principal components of\n// acoustically inverted tube shapes; log-area cosine coefficients around the neutral tract). Do not edit.\nconst MODES = ' + JSON.stringify(out) + ';\nif (typeof module !== \'undefined\') module.exports = MODES;\n');
console.log('wrote src/audio/modes.js from', n, 'frames');

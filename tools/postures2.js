// postures2.js OUT_REPORT.md SHAPES.json:LIST.json [...] - vowel postures measured on a real voice.
// For every recording, the inverted tube shapes in the heart of each vowel (« je », « dis » and the last word) are
// projected onto the learned modes and averaged per vowel. Writes src/audio/postures2.js.
'use strict';
const fs = require('fs'), path = require('path');
const MO = require('../src/audio/modes.js'), PR = require('./prosody.js');
const M = 8;
const VOW = { pas: 'a', bas: 'a', tas: 'a', cas: 'a', gars: 'a', fa: 'a', va: 'a', 'ça': 'a', chat: 'a', ma: 'a', la: 'a', rat: 'a',
  pie: 'i', bu: 'y', 'thé': 'e', qui: 'i', gui: 'i', 'fée': 'e', vie: 'i', si: 'i', chez: 'e', mie: 'i', lit: 'i', riz: 'i',
  pou: 'u', bout: 'u', tout: 'u', cou: 'u', 'goût': 'u', fou: 'u', vous: 'u', sous: 'u', chou: 'u', mou: 'u', loup: 'u', roux: 'u',
  pont: 'o~', bon: 'o~', ton: 'o~', quand: 'a~', gant: 'a~', fond: 'o~', vont: 'o~', son: 'o~', chant: 'a~', mon: 'o~', long: 'o~', rond: 'o~',
  paix: 'E', pot: 'o', pu: 'y', peu: '2', pain: 'e~', paon: 'a~' };
const project = x => { const c = x.slice(1), b = []; for (let j = 0; j < M; j++) { let s = 0; for (let k = 0; k < MO.K; k++) s += (c[k] - MO.mean[k]) * MO.modes[j][k]; b.push(s / MO.sd[j]); } return [x[0], ...b]; };
const acc = {};
const add = (v, p) => { (acc[v] = acc[v] || []).push(p); };
for (const pair of process.argv.slice(3)) {
  const [sf, lf] = pair.split(':'), S = JSON.parse(fs.readFileSync(sf, 'utf8')), L = JSON.parse(fs.readFileSync(lf, 'utf8')), root = path.dirname(path.dirname(lf));
  const byFile = {}; for (const it of L.items) byFile[path.basename(it.file)] = it;
  for (const u of S.utts) {
    const it = byFile[u.file]; if (!it) continue;
    const m = PR.measure(path.resolve(root, it.file), it.word); if (!m) continue;
    const take = (t0, t1, v) => { for (const f of u.frames) if (f.t >= t0 && f.t <= t1) add(v, project(f.x)); };
    take(m.nuclei[0] + .06, m.nuclei[0] + .14, '@');           // je
    take(m.nuclei[1] + .06, m.nuclei[1] + .14, 'i');           // dis
    if (VOW[it.word]) take(m.nuclei[2] + .08, m.nuclei[2] + .22, VOW[it.word]);
  }
}
const out = {}, rows = [];
for (const [v, list] of Object.entries(acc)) {
  const mean = list[0].map((_, k) => list.reduce((s, p) => s + p[k], 0) / list.length);
  out[v.replace('~', 'N')] = mean.map(x => +x.toFixed(3));
  rows.push(`| ${v} | ${list.length} | ${mean.map(x => x.toFixed(2)).join(' ')} |`);
}
fs.writeFileSync(path.resolve(__dirname, '../src/audio/postures2.js'), '// postures2.js - generated by tools/postures2.js: vowel postures measured on a real voice (log lip opening, then the\n// first 8 learned modes in standard deviations). Do not edit.\nconst POSTURES2 = ' + JSON.stringify(out) + ';\nif (typeof module !== \'undefined\') module.exports = POSTURES2;\n');
fs.writeFileSync(process.argv[2], '# Voyelles mesurées sur une voix réelle\n\nMoyenne des formes inversées au cœur de chaque voyelle, projetées sur les 8 modes appris (log ouverture des lèvres, puis b1..b8 en écarts-types).\n\n| voyelle | tranches | posture |\n|---|---|---|\n' + rows.join('\n') + '\n');
console.log(rows.join('\n'));

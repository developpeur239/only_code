// calibrate.js - sets the loudness of every consonant's noise source by measurement.
// Each consonant is sung between two /a/ on one note; its level is measured against the vowel and the
// source gain is corrected until it lands on its target. Writes src/audio/consgain.js and qa/consonants.md.
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
global.POSTURES = require('../src/audio/postures.js');
global.CONSGAIN = {};
for (const k in require.cache) if (k.endsWith('consgain.js')) delete require.cache[k];
const V = require('../src/audio/voice.js'), D = require('./dsp.js');

// dB against the vowel. fricatives: mean level through the consonant; stops: the first 10 ms after release
// (approximate relative intensities of French consonants in sung, sustained context)
const FRIC = { s: -14, z: -18, S: -12, Z: -16, f: -26, v: -24, R: -16 };
const BURST = { p: -14, t: -8, k: -9, b: -18, d: -12, g: -12 };

function measure(c, singer = 'grandpa') {
  const syl = [{ ph: ['a'], midi: 52, t0: .4, t1: 1.0, dyn: .6 }, { ph: [c, 'a'], midi: 52, t0: 1.3, t1: 1.9, dyn: .6 }];
  // the noise alone: the same performance rendered with and without its turbulence and burst sources
  const tr = [], r = V.sing(singer, syl, { trace: tr }), d = V.sing(singer, syl, { dry: true }), x = r.pcm, y = d.pcm, seg = V.plan(syl).find(s => s.ph === c), at = t => Math.round((t - r.t0) * 44100);
  const vow = D.rmsDb(x, at(.6), at(.9));
  const noise = (a, b) => { const pw = Math.pow(10, D.rmsDb(x, at(a), at(b)) / 10), pd = Math.pow(10, D.rmsDb(y, at(a), at(b)) / 10); return 10 * Math.log10(Math.max(pw - pd, 1e-20)) - vow; };
  // the real release: the first moment after the closure when the passage opens again
  const shut = tr.findIndex(q => q[0] > seg.a && q[6] < .002), rel = shut < 0 ? seg.b : (tr.slice(shut).find(q => q[6] > .002) || [seg.b])[0];
  return { rel, fric: noise(seg.a + .015, seg.b - .01), burst: noise(rel, rel + .01), voice: D.rmsDb(y, at(seg.a + .015), at(seg.b - .01)) - vow };
}
const G = {};
const rows = [];
for (const [c, tgt] of Object.entries(FRIC)) {
  let g = .01; let m;
  for (let it = 0; it < 8; it++) { CONSGAIN[c] = { g }; V.CONS[c].g = g; m = measure(c).fric; if (Math.abs(m - tgt) < .5) break; g *= Math.pow(10, clampDb(tgt - m) / 20); }
  G[c] = { g: +g.toPrecision(4) }; rows.push(`| ${c} | bruit de friction | ${tgt} dB | ${m.toFixed(1)} dB |`);
}
for (const [c, tgt] of Object.entries(BURST)) {
  let g = .1; let m;
  for (let it = 0; it < 8; it++) { V.CONS[c].gb = g; m = measure(c).burst; if (Math.abs(m - tgt) < .5) break; g *= Math.pow(10, clampDb(tgt - m) / 20); }
  G[c] = { gb: +g.toPrecision(4) }; rows.push(`| ${c} | explosion (10 ms) | ${tgt} dB | ${m.toFixed(1)} dB |`);
}
function clampDb(d) { return Math.max(-30, Math.min(30, d)); }
fs.writeFileSync(path.join(ROOT, 'src/audio/consgain.js'), '// consgain.js - generated by tools/calibrate.js. Do not edit.\n// g: turbulence source gain, gb: release burst gain\nconst CONSGAIN = ' + JSON.stringify(G) + ';\nif (typeof module !== \'undefined\') module.exports = CONSGAIN;\n');
fs.writeFileSync(path.join(ROOT, 'qa/consonants.md'), '# Consonnes : niveaux calibrés\n\nNiveau mesuré par rapport à la voyelle /a/ voisine, chanté sur une seule note par le grand-père.\n\n| consonne | mesure | cible | obtenu |\n|---|---|---|---|\n' + rows.join('\n') + '\n');
console.log(rows.join('\n'));
